/**
 * 현재 캐릭터 정보와 말투 규칙을 붙인 최종 시스템 프롬프트.
 * 다른 캐릭터의 말투가 섞이지 않도록 현재 캐릭터의 voiceGuide만 넣습니다.
 */
export function buildSystemPrompt(counselorId: CounselorId): string {
  const profile = COUNSELOR_PROFILES[counselorId];
  return `${COUNSELOR_SYSTEM_INSTRUCTION}
[현재 캐릭터]
- 이름: '${profile.name}' (${profile.species})
- 특징: ${profile.personality}
- 슬로건: "${profile.tagline}"

[현재 캐릭터의 말투]
${profile.voiceGuide.map((rule) => `- ${rule}`).join('\n')}
- 말투 예시: "${profile.sampleLine}"

답변 시 선생님이 아닌 다정하고 든든한 친구 '${profile.name}'의 말투를 끝까지 유지하고, 반말로만 답한다.`;
}

/**
 * 네트워크 장애 또는 오프라인 시 사용할 안전한 지능형 로컬 응답 엔진
 */
export function getLocalFallbackResponse(
  counselorId: CounselorId,
  userMessage: string,
  riskLevel: 'safe' | 'concern' | 'crisis'
) {
  const profile = COUNSELOR_PROFILES[counselorId] ?? COUNSELOR_PROFILES.cat;

  if (riskLevel === 'crisis') {
    return {
      message: `${profile.name}는 네 이야기를 듣고 정말 많이 걱정돼. 지금 네가 느끼는 아픔은 혼자 짊어질 일이 아니야. 비밀이 보장되고 너를 지켜줄 수 있는 24시간 청소년 전문 상담 전화(1388, 109)에 지금 바로 연락해 볼래? ${profile.name}가 꼭 곁에 있을게.`,
      suggestedKeywords: ['도움이 필요해', '1388 전화할래', '조금 더 이야기할래'] as [string, string, string],
      riskLevel: 'crisis' as const,
      shouldOfferReferral: true,
      referralStage: 3 as const,
    };
  }

  if (riskLevel === 'concern') {
    return {
      message: `혼자서 속으로 많이 삭이고 힘들었겠다. ${profile.name}한테 이렇게 털어놓아 줘서 고마워. 어떤 부분이 가장 무겁게 느껴졌는지 조금 더 들려줄 수 있어? 필요하면 교내 Wee클래스나 전문 상담 선생님과도 익명으로 이야기해 볼 수 있어.`,
      suggestedKeywords: ['친구 관계 때문에', '공부 스트레스야', '그냥 마음이 답답해'] as [string, string, string],
      riskLevel: 'concern' as const,
      shouldOfferReferral: true,
      referralStage: 2 as const,
    };
  }

  // Safe everyday response
  if (userMessage.includes('고민') || userMessage.includes('힘들') || userMessage.includes('어려')) {
    return {
      message: `어떤 고민이든 네 마음에 부담이 됐다면 충분히 이야기할 가치가 있어. 사소하다고 생각하지 말고 ${profile.name}한테 편하게 털어놓아 줘. 지금 제일 먼저 떠오르는 생각은 뭐야?`,
      suggestedKeywords: ['시험이랑 성적', '친구와의 일', '가족 문제야'] as [string, string, string],
      riskLevel: 'safe' as const,
      shouldOfferReferral: false,
    };
  }

  return {
    message: `그랬구나. 이야기를 들려줘서 고마워. ${profile.name}가 조용히 네 곁에서 귀 기울이고 있어. 그 일 때문에 마음속에 어떤 기분이 가장 크게 들었어?`,
    suggestedKeywords: ['불안하고 답답해', '화가 조금 나', '그냥 지쳤어'] as [string, string, string],
    riskLevel: 'safe' as const,
    shouldOfferReferral: false,
  };
}
